{-# LANGUAGE TemplateHaskell #-}

module Lamdera.Version where

import GitHash

import qualified Ext.Common
import qualified Elm.Version as V


type Version = (Int, Int, Int)

raw :: (Int, Int, Int)
raw = (1,5,0)


rawToString :: (Int, Int, Int) -> String
rawToString (m,mi,p) =
  show m <> "." <> show mi <> "." <> show p


short :: String
short = rawToString raw


medium :: String
medium = "lamdera-" <> short <> "-" <> elm


full :: String
full =
  let
    gi = $$tGitInfoCwd
    dirty | giDirty gi = "-dirty"
          | otherwise  = ""
  in
  concat
    [ medium, "-", Ext.Common.os, "-", Ext.Common.arch, "-", giHash gi, dirty
    , " (", giCommitDate gi, ")"
    , " (branch:", giBranch gi, ")"
    ]


elm :: String
elm =
  V.toChars V.compiler


{-| The key for every compiled-code cache: package artifacts in ELM_HOME
(`artifacts.<cacheKey>.dat`) and the project's `elm-stuff/<cacheKey>/`.

It is the version string plus the format tag of the Wire3 codec IR that the compiler
stores in every module's objects (Lamdera.Wire3.Direct). Caches written by a compiler
that stores no IR, or an older IR format, must never be reused: their types would
silently fall back to the slow Elm codecs. Bump `wire3IrTag` whenever the IR's stored
format changes.

Only cache paths use this. The version string (`medium`, `lamdera --version`, the
"Generated by" header in compiled JS) is unchanged.
-}
cacheKey :: String
cacheKey =
  medium <> "-" <> wire3IrTag


wire3IrTag :: String
wire3IrTag =
  "w3ir1"


artifacts :: String
artifacts =
  "artifacts." <> cacheKey <> ".dat"


resetPatch :: V.Version -> V.Version
resetPatch (V.Version major minor _patch) =
  V.Version major minor 0
