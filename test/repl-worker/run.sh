#!/bin/sh
# The REPL inside `lamdera live`, end to end: start `lamdera live` on a Lamdera app
# and on a plain Elm app (test/scenario-empty-lamdera-init, test/scenario-empty-elm-init,
# both with elm.json at 0.19.1, plus a project module ReplHelpers), drive the REPL
# worker the way the live UI does (harness.js) and compare every answer with
# expected.json.
#
# It also checks what the worker asked the live server for: nothing under a 0.19.2
# path, registry.dat and every package's compiler artifacts from the 0.19.3 tree,
# and no package source at all (the compiler's artifacts were reused, so nothing had
# to be compiled again in the worker).
#
#   LAMDERA=<lamdera binary> test/repl-worker/run.sh
#
# ELM_HOME is a fresh scratch directory holding only a 0.19.3 tree, seeded with the
# package sources (not artifacts or registry) of SEED_ELM_HOME's 0.19.3 tree when it
# has one (default ~/.elm), so the run works offline once those exist.
# Exit status 0 = all pass. KEEP=1 keeps the scratch directory.
set -u

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
L=${LAMDERA:-lamdera}
N=${NODE:-node}
seed=${SEED_ELM_HOME:-$HOME/.elm}
port=${PORT:-8740}
work=$(mktemp -d "${TMPDIR:-/tmp}/lamdera-repl-worker.XXXXXX")
[ -n "${KEEP:-}" ] || trap 'rm -rf "$work"' EXIT

export ELM_HOME="$work/elm-home"
mkdir -p "$ELM_HOME/0.19.3/packages"
if [ -d "$seed/0.19.3/packages" ]; then
  (cd "$seed/0.19.3/packages" && find . -mindepth 3 -maxdepth 3 -type d) | while read -r p; do
    mkdir -p "$ELM_HOME/0.19.3/packages/$p"
    cp -R "$seed/0.19.3/packages/$p/." "$ELM_HOME/0.19.3/packages/$p/"
  done
  find "$ELM_HOME" -name 'artifacts.*' -delete
fi
unset LAMDERA_APP_NAME

echo "lamdera: $("$L" --version-full)"
echo "scratch: $work"
fail=0

for app in lamdera plain; do
  # The page to load first: a Lamdera app's live page, and for a plain Elm app (whose
  # live page is the Lamdera harness, which needs Frontend/Backend) its main module,
  # served reactor-style.
  case $app in
    lamdera) src="$root/test/scenario-empty-lamdera-init"; page=/ ;;
    plain)   src="$root/test/scenario-empty-elm-init"; page=/src/Main.elm ;;
  esac
  dir="$work/$app"
  mkdir -p "$dir"
  cp -R "$src/elm.json" "$src/src" "$dir/"
  cp "$here/ReplHelpers.elm" "$dir/src/"
  grep -q '"elm-version": "0.19.1"' "$dir/elm.json" || { echo "$app: expected an elm.json at 0.19.1"; exit 2; }
  # The live page of a Lamdera app (elm-stuff/lamdera/Lamdera/Live.elm) imports Bytes,
  # which the fixture only has as an indirect dependency, as `lamdera init` apps do not.
  if [ $app = lamdera ]; then
    $N -e 'const f = process.argv[1], j = JSON.parse(require("fs").readFileSync(f, "utf8")), d = j.dependencies;
      d.direct["elm/bytes"] = d.indirect["elm/bytes"]; delete d.indirect["elm/bytes"];
      require("fs").writeFileSync(f, JSON.stringify(j, null, 4))' "$dir/elm.json"
  fi

  (cd "$dir" && exec "$L" live --port=$port) > "$work/$app-live.log" 2>&1 &
  pid=$!
  if ! curl -s --retry 60 --retry-connrefused --retry-delay 1 -o "$work/$app-page.html" http://localhost:$port$page; then
    echo "$app: lamdera live did not start"; cat "$work/$app-live.log"; kill $pid; fail=1; continue
  fi
  if grep -q "Elm.Errors.init" "$work/$app-page.html" || ! grep -q "Generated by lamdera" "$work/$app-page.html"; then
    echo "FAIL  $app: $page did not compile"; fail=1
  fi

  $N "$here/harness.js" http://localhost:$port "$here/inputs-$app.json" "$work/$app-out.json" > "$work/$app-harness.log" 2>&1
  kill $pid; wait $pid 2>/dev/null
  port=$((port + 1))
  $N "$here/check.js" "$app" "$here/expected-$app.json" "$work/$app-out.json" "$work/$app-live.log" || fail=1
done

[ $fail = 0 ] && echo "REPL WORKER OK" || echo "REPL WORKER FAILED"
exit $fail
